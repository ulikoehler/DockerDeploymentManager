fn restic_env_script_prefix(cfg: &AppConfig, svc: &Service) -> String {
    let repo = repository_for(&cfg.backup, &svc.name);
    let mut s = format!(
        "cd {dir} && export RESTIC_REPOSITORY={repo} RESTIC_PASSWORD_FILE={pw}",
        dir = shell_quote(&svc.host_dir.to_string_lossy()),
        repo = shell_quote(&repo),
        pw = shell_quote(&svc.host_dir.join(PASSWORD_FILE).to_string_lossy()),
    );
    for (k, v) in &cfg.backup.extra_env {
        s.push_str(&format!(" {k}={}", shell_quote(v)));
    }
    s
}

/// `restic snapshots --json` for a service.
pub async fn snapshots(
    cfg: &AppConfig,
    host: &Arc<dyn HostExec>,
    svc: &Service,
    restic_bin: &str,
) -> Result<serde_json::Value> {
    let script = format!(
        "{} && {} snapshots --json",
        restic_env_script_prefix(cfg, svc),
        shell_quote(restic_bin)
    );
    let out = host.run("bash", &["-c".into(), script]).await?;
    if !out.success() {
        anyhow::bail!("restic snapshots failed: {}", out.stderr.trim());
    }
    Ok(serde_json::from_str(&out.stdout).unwrap_or(serde_json::json!([])))
}

/// Build the host script for forget --prune.
pub fn forget_script(cfg: &AppConfig, svc: &Service, restic_bin: &str) -> String {
    let mut extra = String::new();
    if let Some(r) = &cfg.backup.retention {
        if let Some(k) = r.keep_last {
            extra.push_str(&format!(" --keep-last {k}"));
        }
        if let Some(k) = r.keep_daily {
            extra.push_str(&format!(" --keep-daily {k}"));
        }
        if let Some(k) = r.keep_weekly {
            extra.push_str(&format!(" --keep-weekly {k}"));
        }
        if let Some(k) = r.keep_monthly {
            extra.push_str(&format!(" --keep-monthly {k}"));
        }
    }
    format!(
        "{} && {} forget --prune{}",
        restic_env_script_prefix(cfg, svc),
        shell_quote(restic_bin),
        extra
    )
}

/// Snapshot id validity — shared by every restic invocation that takes
/// one on the command line. `latest` is restic's special selector.
pub fn valid_snapshot(snapshot: &str) -> Result<()> {
    if snapshot == "latest" {
        return Ok(());
    }
    if snapshot.is_empty()
        || snapshot
            .chars()
            .any(|c| !(c.is_ascii_alphanumeric() || c == '-' || c == '_'))
    {
        anyhow::bail!("invalid snapshot id");
    }
    Ok(())
}

/// A path inside the snapshot (`ls` dir arg, `--include` pattern): no
/// traversal, no flag-like leading dash, nothing the shell could expand
/// into a second token.
fn valid_snap_path(p: &str, what: &str) -> Result<()> {
    if p.is_empty()
        || p.contains("..")
        || p.starts_with('-')
        || p.contains('\\')
        || p.contains('\0')
    {
        anyhow::bail!("invalid snapshot {what} '{p}'");
    }
    Ok(())
}

/// `restic ls <snapshot> [path]` — list files inside a snapshot, JSON out.
pub fn ls_script(
    cfg: &AppConfig,
    svc: &Service,
    restic_bin: &str,
    snapshot: &str,
    path: Option<&str>,
) -> Result<String> {
    valid_snapshot(snapshot)?;
    let mut s = format!(
        "{} && {} ls --json {}",
        restic_env_script_prefix(cfg, svc),
        shell_quote(restic_bin),
        shell_quote(snapshot),
    );
    if let Some(p) = path.filter(|p| !p.is_empty()) {
        valid_snap_path(p, "path")?;
        s.push_str(&format!(" {}", shell_quote(p)));
    }
    Ok(s)
}

/// Build the host script for `restic restore`. `includes` selects paths
/// inside the snapshot (restic `--include` patterns); empty = full restore.
pub fn restore_script(
    cfg: &AppConfig,
    svc: &Service,
    restic_bin: &str,
    snapshot: &str,
    target_dir: &str,
    includes: &[String],
) -> Result<String> {
    valid_snapshot(snapshot)?;
    let rel_ok = valid_rel_path(target_dir);
    let abs_ok = PathBuf::from(target_dir).is_absolute() && !target_dir.contains("..");
    if !rel_ok && !abs_ok {
        anyhow::bail!("target_dir must be a relative or absolute path without '..'");
    }
    let mut s = format!(
        "{} && {} restore {} --target {}",
        restic_env_script_prefix(cfg, svc),
        shell_quote(restic_bin),
        shell_quote(snapshot),
        shell_quote(target_dir)
    );
    for i in includes {
        valid_snap_path(i, "include")?;
        s.push_str(&format!(" --include {}", shell_quote(i)));
    }
    Ok(s)
}

/// Script to run the backup now.
pub fn run_script(svc: &Service) -> String {
    shell_quote(&svc.host_dir.join(SCRIPT_FILE).to_string_lossy()).to_string()
}

/// Expand `${VAR}` in a dump command from an env file's contents.
/// (Used for validation of meta.yaml at save time.)
#[allow(dead_code)]
pub fn expand_env_vars(cmd: &[String], env: &HashMap<String, String>) -> Vec<String> {
    cmd.iter()
        .map(|a| {
            let mut s = a.clone();
            for (k, v) in env {
                s = s.replace(&format!("${{{k}}}"), v);
            }
            s
        })
        .collect()
}

/// Structural validation of `stdin_dumps`. The dump service name and
/// command argv are rendered *unquoted* into a root-run shell script
/// (`render_backup_script`), so every interpolated value must be free of
/// shell metacharacters. `${VAR}` references are intentional — they expand
/// at runtime from the sourced env file — and are allowed in that exact
/// form only.
pub fn validate_dumps(dumps: &[StdinDump]) -> Result<()> {
    for d in dumps {
        if d.filename.is_empty() || d.filename.contains('/') || d.filename.contains("..") {
            anyhow::bail!("invalid stdin_dump filename '{}'", d.filename);
        }
        check_dump_piece(&d.service, "service")?;
        if d.command.is_empty() {
            anyhow::bail!("stdin_dump '{}' has empty command", d.filename);
        }
        for arg in &d.command {
            check_dump_piece(arg, "command")?;
        }
        if let Some(envf) = &d.env_file {
            if !crate::services::valid_rel_path(envf) {
                anyhow::bail!("invalid stdin_dump env_file '{envf}'");
            }
        }
    }
    Ok(())
}

/// One argv piece rendered into the backup script: alnum + common flag/path
/// punctuation, plus `${VAR}` placeholders (validated as a whole so `$()`,
/// backticks and other expansions can't slip in).
fn check_dump_piece(s: &str, what: &str) -> Result<()> {
    static RE: std::sync::OnceLock<regex::Regex> = std::sync::OnceLock::new();
    let re = RE.get_or_init(|| {
        regex::Regex::new(r"^[A-Za-z0-9_./:@%+=,-]*(\$\{[A-Za-z_][A-Za-z0-9_]*\}[A-Za-z0-9_./:@%+=,-]*)*$")
            .unwrap()
    });
    if s.is_empty() || !re.is_match(s) {
        anyhow::bail!("invalid stdin_dump {what} value '{s}'");
    }
    Ok(())
}

/// Check dump service names against the compose file's service names.
/// Called agent-side where the compose file is available.
pub fn validate_dump_services(dumps: &[StdinDump], compose_yaml: &str) -> Result<()> {
    let doc: serde_yaml::Value = serde_yaml::from_str(compose_yaml)?;
    let services: Vec<String> = doc
        .get("services")
        .and_then(|s| s.as_mapping())
        .map(|m| {
            m.keys()
                .filter_map(|k| k.as_str().map(str::to_string))
                .collect()
        })
        .unwrap_or_default();
    for d in dumps {
        if !services.iter().any(|s| s == &d.service) {
            anyhow::bail!("stdin_dump service '{}' not in compose services", d.service);
        }
    }
    Ok(())
}

