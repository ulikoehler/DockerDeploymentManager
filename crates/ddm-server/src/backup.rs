pub fn render_backup_units(cfg: &AppConfig, svc: &Service) -> (String, String) {
    let (svc_unit, timer_unit) = unit_names(&cfg.backup, &svc.name);
    let script = svc.host_dir.join(SCRIPT_FILE);
    let service_unit = format!(
        "[Unit]\nDescription=Backup for {name} (ddm)\nRequires=docker.service\nAfter=docker.service\n\n[Service]\nType=oneshot\nWorkingDirectory={dir}\nExecStart={script}\n",
        name = svc.name,
        dir = svc.host_dir.to_string_lossy(),
        script = script.to_string_lossy(),
    );
    let timer_unit_content = format!(
        "[Unit]\nDescription=Backup timer for {name} (ddm)\n\n[Timer]\nOnCalendar={cal}\nPersistent=true\n\n[Install]\nWantedBy=timers.target\n",
        name = svc.name,
        cal = cfg.backup.on_calendar,
    );
    let _ = svc_unit;
    let _ = timer_unit;
    (service_unit, timer_unit_content)
}

