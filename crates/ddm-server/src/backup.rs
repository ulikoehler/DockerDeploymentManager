    #[test]
    fn valid_dump_names() {
        let dumps = vec![StdinDump {
            filename: "a.sql".into(),
            service: "db".into(),
            command: vec!["pg_dump".into()],
            env_file: None,
        }];
        assert!(validate_dumps(&dumps).is_ok());
        let compose = "services:\n  db:\n    image: postgres\n";
        assert!(validate_dump_services(&dumps, compose).is_ok());
        // service must exist in the compose file
        assert!(validate_dump_services(&dumps, "services:\n  other:\n    image: x\n").is_err());
        let bad = vec![StdinDump {
            filename: "../x".into(),
            service: "db".into(),
            command: vec!["x".into()],
            env_file: None,
        }];
        assert!(validate_dumps(&bad).is_err());
        // shell metacharacters in the service name or argv are rejected
        let inject = vec![StdinDump {
            filename: "a.sql".into(),
            service: "db; touch /tmp/pwned".into(),
            command: vec!["pg_dump".into()],
            env_file: None,
        }];
        assert!(validate_dumps(&inject).is_err());
        let inject_cmd = vec![StdinDump {
            filename: "a.sql".into(),
            service: "db".into(),
            command: vec!["$(id)".into()],
            env_file: None,
        }];
        assert!(validate_dumps(&inject_cmd).is_err());
        let backtick = vec![StdinDump {
            filename: "a.sql".into(),
            service: "db".into(),
            command: vec!["pg_dump `id`".into()],
            env_file: None,
        }];
        assert!(validate_dumps(&backtick).is_err());
        // intended ${VAR} expansion still allowed
        let envvar = vec![StdinDump {
            filename: "a.sql".into(),
            service: "db".into(),
            command: vec!["pg_dump".into(), "-U".into(), "${PGUSER}".into()],
            env_file: Some(".env".into()),
        }];
        assert!(validate_dumps(&envvar).is_ok());
        // env_file must be a relative in-service path
        let badenv = vec![StdinDump {
            filename: "a.sql".into(),
            service: "db".into(),
            command: vec!["pg_dump".into()],
            env_file: Some("../../etc/shadow".into()),
        }];
        assert!(validate_dumps(&badenv).is_err());
    }

    #[test]
    fn restore_target_validation() {
        let tmp = tempfile::tempdir().unwrap();
        let s = svc(tmp.path());
        let c = cfg();
        assert!(restore_script(&c, &s, "restic", "latest", "/tmp/restore-1", &[]).is_ok());
        assert!(restore_script(&c, &s, "restic", "abc;rm", "/tmp/x", &[]).is_err());
        assert!(restore_script(&c, &s, "restic", "latest", "rel/path", &[]).is_ok());
        assert!(restore_script(&c, &s, "restic", "latest", "/tmp/../x", &[]).is_err());
        // selective restore: include patterns are validated and quoted
        let inc = vec!["data".to_string(), "docker-compose.yml".to_string()];
        let out = restore_script(&c, &s, "restic", "latest", "/tmp/r", &inc).unwrap();
        assert!(out.contains("--include 'data'") && out.contains("--include 'docker-compose.yml'"));
        let bad = vec!["../escape".to_string()];
        assert!(restore_script(&c, &s, "restic", "latest", "/tmp/r", &bad).is_err());
        let bad = vec!["-rf".to_string()];
        assert!(restore_script(&c, &s, "restic", "latest", "/tmp/r", &bad).is_err());
        // restic ls: snapshot listing
        assert!(ls_script(&c, &s, "restic", "latest", None).is_ok());
        assert!(ls_script(&c, &s, "restic", "latest", Some("data/x")).is_ok());
        assert!(ls_script(&c, &s, "restic", "latest", Some("../x")).is_err());
        assert!(ls_script(&c, &s, "restic", "abc;rm", None).is_err());
    }
