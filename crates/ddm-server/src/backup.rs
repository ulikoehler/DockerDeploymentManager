fn restic_env_script_prefix(cfg: &AppConfig, svc: &Service) -> String {
    let repo = repository_for(&cfg.backup, &svc.name);
    let mut s = format!(
        "cd {dir} && export RESTIC_REPOSITORY={repo} RESTIC_PASSWORD_FILE={pw}",
        dir = shell_quote(&svc.host_dir.to_string_lossy()),
        repo = shell_quote(&repo),
        pw = shell_quote(&svc.host_dir.join(PASSWORD_FILE).to_string_lossy()),
    );
    for (k, v) in &cfg.backup.extra_env {
        s.push_str(&format!(" {k}={}", shell_quote(v)));
    }
    s
}

/// `restic snapshots --json` for a service.
pub async fn snapshots(
    cfg: &AppConfig,
    host: &Arc<dyn HostExec>,
    svc: &Service,
    restic_bin: &str,
) -> Result<serde_json::Value> {
    let script = format!(
        "{} && {} snapshots --json",
        restic_env_script_prefix(cfg, svc),
        shell_quote(restic_bin)
    );
    let out = host.run("bash", &["-c".into(), script]).await?;
    if !out.success() {
        anyhow::bail!("restic snapshots failed: {}", out.stderr.trim());
    }
    Ok(serde_json::from_str(&out.stdout).unwrap_or(serde_json::json!([])))
}

/// Build the host script for forget --prune.
pub fn forget_script(cfg: &AppConfig, svc: &Service, restic_bin: &str) -> String {
    let mut extra = String::new();
    if let Some(r) = &cfg.backup.retention {
        if let Some(k) = r.keep_last {
            extra.push_str(&format!(" --keep-last {k}"));
        }
        if let Some(k) = r.keep_daily {
            extra.push_str(&format!(" --keep-daily {k}"));
        }
        if let Some(k) = r.keep_weekly {
            extra.push_str(&format!(" --keep-weekly {k}"));
        }
        if let Some(k) = r.keep_monthly {
            extra.push_str(&format!(" --keep-monthly {k}"));
        }
    }
    format!(
        "{} && {} forget --prune{}",
        restic_env_script_prefix(cfg, svc),
        shell_quote(restic_bin),
        extra
    )
}

/// Build the host script for `restic restore`.
pub fn restore_script(
    cfg: &AppConfig,
    svc: &Service,
    restic_bin: &str,
    snapshot: &str,
    target_dir: &str,
) -> Result<String> {
    if snapshot
        .chars()
        .any(|c| !(c.is_ascii_alphanumeric() || c == '-'))
        && snapshot != "latest"
    {
        anyhow::bail!("invalid snapshot id");
    }
    let target = PathBuf::from(target_dir);
    if !target.is_absolute() || target_dir.contains("..") {
        anyhow::bail!("target_dir must be an absolute path without '..'");
    }
    Ok(format!(
        "{} && {} restore {} --target {}",
        restic_env_script_prefix(cfg, svc),
        shell_quote(restic_bin),
        shell_quote(snapshot),
        shell_quote(target_dir)
    ))
}

/// Script to run the backup now.
pub fn run_script(svc: &Service) -> String {
    shell_quote(&svc.host_dir.join(SCRIPT_FILE).to_string_lossy()).to_string()
}

/// Expand `${VAR}` in a dump command from an env file's contents.
/// (Used for validation of meta.yaml at save time.)
#[allow(dead_code)]
pub fn expand_env_vars(cmd: &[String], env: &HashMap<String, String>) -> Vec<String> {
    cmd.iter()
        .map(|a| {
            let mut s = a.clone();
            for (k, v) in env {
                s = s.replace(&format!("${{{k}}}"), v);
            }
            s
        })
        .collect()
}

/// Validate a StdinDump list against a compose file's service names.
#[allow(dead_code)]
pub fn validate_dumps(dumps: &[StdinDump], compose_services: &[String]) -> Result<()> {
    for d in dumps {
        if d.filename.is_empty() || d.filename.contains('/') || d.filename.contains("..") {
            anyhow::bail!("invalid stdin_dump filename '{}'", d.filename);
        }
        if !compose_services.iter().any(|s| s == &d.service) {
            anyhow::bail!("stdin_dump service '{}' not in compose services", d.service);
        }
        if d.command.is_empty() {
            anyhow::bail!("stdin_dump '{}' has empty command", d.filename);
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::RetentionPolicy;

    fn cfg() -> AppConfig {
        let mut c = AppConfig::default();
        c.paths.services_root = "/tmp/svc".into();
        c.paths.host_services_root = Some("/opt/services".into());
        c.backup.enabled = true;
        c.backup.repository_base = "rest:http://restic:pw@10.0.0.1:8000/".into();
        c.backup.retention = Some(RetentionPolicy {
            keep_last: Some(7),
            keep_daily: Some(7),
            keep_weekly: Some(4),
            keep_monthly: None,
        });
        c.systemd.compose_binary = "/usr/bin/docker-compose".into();
        c
    }

    fn svc(dir: &Path) -> Service {
        let compose = dir.join("docker-compose.yml");
        std::fs::write(&compose, "services:\n  db:\n    image: postgres\n").unwrap();
        Service {
            name: "pg-app".into(),
            dir: dir.to_path_buf(),
            host_dir: PathBuf::from("/opt/services/pg-app"),
            compose_path: compose,
            meta: Default::default(),
        }
    }

    #[test]
    fn repo_template() {
        let c = cfg();
        assert_eq!(
            repository_for(&c.backup, "web-1"),
            "rest:http://restic:pw@10.0.0.1:8000/web-1"
        );
        let mut c2 = c.clone();
        c2.backup.repository_template = Some("s3:bucket/{service}".into());
        assert_eq!(repository_for(&c2.backup, "x"), "s3:bucket/x");
    }

    #[test]
    fn render_script() {
        let tmp = tempfile::tempdir().unwrap();
        let s = svc(tmp.path());
        let mut bcfg = ServiceBackupConfig {
            paths: vec!["docker-compose.yml".into(), "data".into()],
            ..Default::default()
        };
        bcfg.stdin_dumps.push(StdinDump {
            filename: "pg-app.sql".into(),
            service: "db".into(),
            command: vec!["pg_dump".into(), "-U".into(), "${POSTGRES_USER}".into()],
            env_file: Some(".env".into()),
        });
        let script = render_backup_script(&cfg(), &s, &bcfg).unwrap();
        assert!(script.contains("RESTIC_REPOSITORY='rest:http://restic:pw@10.0.0.1:8000/pg-app'"));
        assert!(script.contains("cd '/opt/services/pg-app'"));
        assert!(script.contains("restic init") || script.contains("init"));
        assert!(script.contains("--stdin-filename='pg-app.sql'"));
        assert!(script.contains("--exclude '.restic_password'"));
        assert!(script.contains("--keep-last 7"));
    }

    #[test]
    fn timer_units() {
        let tmp = tempfile::tempdir().unwrap();
        let s = svc(tmp.path());
        let c = cfg();
        let (su, tu) = render_backup_units(&c, &s);
        assert!(su.contains("ExecStart=/opt/services/pg-app/backup.sh"));
        assert!(su.contains("Type=oneshot"));
        assert!(tu.contains("OnCalendar=daily"));
        assert!(tu.contains("WantedBy=timers.target"));
    }

    #[test]
    fn valid_dump_names() {
        let dumps = vec![StdinDump {
            filename: "a.sql".into(),
            service: "db".into(),
            command: vec!["pg_dump".into()],
            env_file: None,
        }];
        assert!(validate_dumps(&dumps, &["db".to_string()]).is_ok());
        let bad = vec![StdinDump {
            filename: "../x".into(),
            service: "db".into(),
            command: vec!["x".into()],
            env_file: None,
        }];
        assert!(validate_dumps(&bad, &["db".to_string()]).is_err());
    }

    #[test]
    fn restore_target_validation() {
        let tmp = tempfile::tempdir().unwrap();
        let s = svc(tmp.path());
        let c = cfg();
        assert!(restore_script(&c, &s, "restic", "latest", "/tmp/restore-1").is_ok());
        assert!(restore_script(&c, &s, "restic", "abc;rm", "/tmp/x").is_err());
        assert!(restore_script(&c, &s, "restic", "latest", "rel/path").is_err());
        assert!(restore_script(&c, &s, "restic", "latest", "/tmp/../x").is_err());
    }
}
