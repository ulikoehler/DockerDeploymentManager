#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct BackupIssue {
    pub code: String,
    pub message: String,
    pub fixable: bool,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct BackupCheckReport {
    pub service: String,
    pub enabled: bool,
    pub password_file: bool,
    pub script: bool,
    pub repo_inited: bool,
    pub timer_exists: bool,
    pub timer_enabled: Option<String>,
    pub timer_active: Option<String>,
    pub last_run: Option<String>,
    pub repository: String,
    pub issues: Vec<BackupIssue>,
}

fn bissue(code: &str, msg: impl Into<String>) -> BackupIssue {
    BackupIssue {
        code: code.to_string(),
        message: msg.into(),
        fixable: true,
    }
}

pub async fn check(cfg: &AppConfig, host: &Arc<dyn HostExec>, svc: &Service) -> BackupCheckReport {
    let bcfg = svc.meta.backup.clone().unwrap_or_default();
    let mut issues = vec![];

    let password_file = svc.dir.join(PASSWORD_FILE).is_file();
    if !password_file {
        issues.push(bissue("password_missing", ".restic_password missing"));
    }
    let script = svc.dir.join(SCRIPT_FILE).is_file();
    if !script {
        issues.push(bissue("script_missing", "backup.sh missing"));
    }
    let repo_inited = svc.dir.join(INITED_FILE).is_file();
    if !repo_inited {
        issues.push(bissue("repo_not_inited", "restic repo not initialized"));
    }

    // restic present on host?
    match host.which("restic").await {
        Ok(None) => issues.push(BackupIssue {
            code: "restic_missing".into(),
            message: "restic binary not found on host".into(),
            fixable: false,
        }),
        Err(e) => issues.push(BackupIssue {
            code: "check_error".into(),
            message: format!("host exec failed: {e:#}"),
            fixable: false,
        }),
        _ => {}
    }

    let (sname, tname) = unit_names(&cfg.backup, &svc.name);
    let sdir = Path::new(&cfg.paths.host_systemd_dir);
    let timer_exists = sdir.join(&tname).is_file();
    if bcfg.schedule_enabled && !timer_exists {
        issues.push(bissue("timer_missing", "backup timer unit missing"));
    }
    let (t_enabled, t_active) = if timer_exists {
        crate::systemd::unit_state(host, &tname).await
    } else {
        (None, None)
    };
    if timer_exists {
        if !matches!(
            t_enabled.as_deref(),
            Some("enabled") | Some("enabled-runtime")
        ) {
            issues.push(bissue("timer_disabled", "timer not enabled"));
        }
        if !matches!(t_active.as_deref(), Some("active")) {
            issues.push(bissue("timer_inactive", "timer not active"));
        }
    }
    let _ = sname;

    // last_run: newest file mtime of .restic_* markers? read from
    // journalctl is heavy — use host `systemctl show -p ExecMainStatus`.
    let last_run = if timer_exists {
        host.run(
            "systemctl",
            &[
                "show".into(),
                sname.clone(),
                "-p".into(),
                "ExecMainStartTimestamp".into(),
            ],
        )
        .await
        .ok()
        .map(|o| {
            o.stdout
                .trim()
                .trim_start_matches("ExecMainStartTimestamp=")
                .to_string()
        })
        .filter(|s| !s.is_empty() && s != "n/a")
    } else {
        None
    };
    if last_run.is_none() && repo_inited {
        issues.push(bissue("never_run", "no backup run recorded"));
    }

    BackupCheckReport {
        service: svc.name.clone(),
        enabled: bcfg.enabled,
        password_file,
        script,
        repo_inited,
        timer_exists,
        timer_enabled: t_enabled,
        timer_active: t_active,
        last_run,
        repository: repository_for(&cfg.backup, &svc.name),
        issues,
    }
}

