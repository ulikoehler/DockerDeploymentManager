/// Render the per-service backup script (TechOverflow style, generalized).
/// All paths are HOST paths.
pub fn render_backup_script(
    cfg: &AppConfig,
    svc: &Service,
    bcfg: &ServiceBackupConfig,
) -> Result<String> {
    let repo = repository_for(&cfg.backup, &svc.name);
    let dir = svc.host_dir.to_string_lossy();
    let compose_file = svc
        .compose_path
        .file_name()
        .map(|s| s.to_string_lossy().to_string())
        .unwrap_or_else(|| "docker-compose.yml".into());
    let restic = if cfg.backup.restic_binary == "auto" {
        "restic".to_string()
    } else {
        shell_quote(&cfg.backup.restic_binary)
    };
    // compose binary: either pinned, or auto-detected at script runtime
    let compose_bin = if cfg.systemd.compose_binary == "auto" {
        "$COMPOSE_BIN".to_string()
    } else {
        shell_quote(&cfg.systemd.compose_binary)
    };

    let mut s = String::new();
    s.push_str("#!/bin/bash\n# generated by ddm — do not edit by hand\n");
    s.push_str("set -euo pipefail\n");
    s.push_str(&format!("export NAME={}\n", shell_quote(&svc.name)));
    s.push_str(&format!(
        "export RESTIC_REPOSITORY={}\n",
        shell_quote(&repo)
    ));
    s.push_str(&format!(
        "export RESTIC_PASSWORD_FILE={}\n",
        shell_quote(&format!("{dir}/{PASSWORD_FILE}"))
    ));
    for (k, v) in &cfg.backup.extra_env {
        if !k
            .chars()
            .enumerate()
            .all(|(i, c)| c == '_' || c.is_ascii_alphanumeric() && (i > 0 || !c.is_ascii_digit()))
        {
            anyhow::bail!("invalid backup extra_env key '{k}'");
        }
        s.push_str(&format!("export {k}={}\n", shell_quote(v)));
    }
    s.push_str(&format!("cd {}\n\n", shell_quote(&dir)));

    // fail closed: never render an unvalidated dump command into a
    // root-executed script, no matter which path stored the config.
    validate_dumps(&bcfg.stdin_dumps)?;
    if cfg.systemd.compose_binary == "auto" {
        s.push_str(
            "if command -v docker-compose >/dev/null 2>&1; then COMPOSE_BIN='docker-compose'; else COMPOSE_BIN='docker compose'; fi\n\n",
        );
    }

    s.push_str(&format!(
        "if [ ! -f \"{INITED_FILE}\" ]; then\n  {restic} init\n  touch {INITED_FILE}\nfi\n\n"
    ));

    // stdin dumps (pg_dump-style)
    for dump in &bcfg.stdin_dumps {
        let mut cmd_parts: Vec<String> = vec![
            format!("{compose_bin} -f {}", shell_quote(&compose_file)),
            "exec".into(),
            "-T".into(),
            dump.service.clone(),
        ];
        cmd_parts.extend(dump.command.iter().cloned());
        let cmdline = cmd_parts.join(" ");
        if let Some(envf) = &dump.env_file {
            s.push_str(&format!("set -a; source {}; set +a\n", shell_quote(envf)));
        }
        // ${VAR} stays literal and expands at runtime from the sourced env file
        s.push_str(&format!(
            "{cmdline} | {restic} --verbose backup --stdin --stdin-filename={}\n\n",
            shell_quote(&dump.filename.replace("{service}", &svc.name))
        ));
    }

    // file backup
    let mut paths: Vec<String> = bcfg.paths.clone();
    if paths.is_empty() {
        paths = vec![compose_file, SCRIPT_FILE.to_string()];
    }
    for p in &paths {
        if !valid_rel_path(p) {
            anyhow::bail!("invalid backup path '{p}'");
        }
    }
    let mut excl: Vec<String> = cfg.backup.excludes.clone();
    excl.extend(bcfg.excludes.clone());
    // never back up the password into the repo
    excl.push(PASSWORD_FILE.to_string());
    let mut cmd = format!("{restic} --verbose backup");
    for p in &paths {
        cmd.push_str(&format!(" {}", shell_quote(p)));
    }
    for e in &excl {
        cmd.push_str(&format!(" --exclude {}", shell_quote(e)));
    }
    s.push_str(&cmd);
    s.push('\n');

    if let Some(r) = &cfg.backup.retention {
        let mut f = format!("\n{restic} forget --prune");
        if let Some(k) = r.keep_last {
            f.push_str(&format!(" --keep-last {k}"));
        }
        if let Some(k) = r.keep_daily {
            f.push_str(&format!(" --keep-daily {k}"));
        }
        if let Some(k) = r.keep_weekly {
            f.push_str(&format!(" --keep-weekly {k}"));
        }
        if let Some(k) = r.keep_monthly {
            f.push_str(&format!(" --keep-monthly {k}"));
        }
        s.push_str(&f);
        s.push('\n');
    }
    Ok(s)
}

pub fn shell_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', "'\\''"))
}

