pub const PASSWORD_FILE: &str = ".restic_password";
pub const INITED_FILE: &str = ".restic_inited";
pub const SCRIPT_FILE: &str = "backup.sh";

/// Repository URL for a service: base + name, or custom template.
pub fn repository_for(cfg: &BackupConfig, service: &str) -> String {
    if let Some(tpl) = &cfg.repository_template {
        tpl.replace("{base}", &cfg.repository_base)
            .replace("{service}", service)
    } else {
        format!("{}{}", cfg.repository_base, service)
    }
}

/// Timer/service unit names for a service backup.
pub fn unit_names(cfg: &BackupConfig, service: &str) -> (String, String) {
    (
        format!("{}-{}.service", cfg.unit_prefix, service),
        format!("{}-{}.timer", cfg.unit_prefix, service),
    )
}

